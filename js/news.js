const NEWS_KEY = 'worst-roommates-news';
const SCROLL_SPEED = 52; // real pixels per second, independent of the simulation speed

export class NewsTicker {
  constructor() {
    this.el = document.getElementById('newsTicker');
    this.viewport = document.getElementById('newsViewport');
    this.track = document.getElementById('newsTrack');
    this.pauseButton = document.getElementById('newsPause');
    this.setting = document.getElementById('newsEnabled');
    this.motion = window.matchMedia('(prefers-reduced-motion: reduce)');
    this.offset = 0;
    this.deck = [];
    this.lastIndex = -1;
    let saved = {};
    try { saved = JSON.parse(localStorage.getItem(NEWS_KEY)) || {}; } catch { /* defaults */ }
    this.enabled = saved.enabled !== false;
    this.paused = saved.paused === true;
    this.hovered = false;
    this.focused = false;
    this.pauseButton.addEventListener('click', () => { this.paused = !this.paused; this.refresh(); this.save(); });
    document.getElementById('newsNext').addEventListener('click', () => this.next());
    this.setting.addEventListener('change', () => { this.enabled = this.setting.checked; this.refresh(); this.save(); });
    this.el.addEventListener('pointerenter', e => { if (e.pointerType === 'mouse') this.hovered = true; });
    this.el.addEventListener('pointerleave', () => { this.hovered = false; });
    this.el.addEventListener('pointerdown', () => { this.focused = false; });
    this.el.addEventListener('focusin', e => { this.focused = e.target.matches(':focus-visible'); });
    this.el.addEventListener('focusout', () => { this.focused = false; });
    // Space activates these controls; Tab must remain available to keyboard readers.
    this.el.addEventListener('keydown', e => e.stopPropagation());
    this.motion.addEventListener('change', () => this.refresh());
    this.refresh();
    this.resizeObserver = new ResizeObserver(() => { this.fill(); this.layout(); });
    for (const el of [this.el, this.viewport, document.getElementById('topbar')]) this.resizeObserver.observe(el);
  }

  get still() { return this.paused || this.motion.matches; }

  save() {
    try { localStorage.setItem(NEWS_KEY, JSON.stringify({ enabled: this.enabled, paused: this.paused })); } catch { /* session only */ }
  }

  headline() {
    if (!this.deck.length) {
      this.deck = NEWS_HEADLINES.map((_, i) => i);
      for (let i = this.deck.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [this.deck[i], this.deck[j]] = [this.deck[j], this.deck[i]];
      }
      if (this.deck[this.deck.length - 1] === this.lastIndex) {
        [this.deck[0], this.deck[this.deck.length - 1]] = [this.deck[this.deck.length - 1], this.deck[0]];
      }
    }
    this.lastIndex = this.deck.pop();
    return NEWS_HEADLINES[this.lastIndex];
  }

  append() {
    const [category, text] = this.headline();
    const item = document.createElement('span');
    item.className = 'newsItem';
    item.title = `Fictional satire: ${text}`;
    const tag = document.createElement('b');
    tag.className = 'newsCategory';
    tag.textContent = category;
    item.append(tag, document.createTextNode(text));
    this.track.appendChild(item);
  }

  fill() {
    if (!this.enabled) return;
    if (!this.track.firstElementChild) this.append();
    if (!this.still) {
      // Buffer beyond both edges, including on very wide displays. Only measure when adding/removing
      // a headline or resizing, never on every animation frame.
      // Bound the buffer too: a missing stylesheet must never block the game's startup.
      while (this.track.children.length < 16 && (this.track.children.length < 3 || this.track.offsetWidth < this.viewport.clientWidth * 2)) this.append();
    }
    for (const item of this.track.children) item.setAttribute('aria-hidden', String(item !== this.track.firstElementChild));
    this.firstWidth = this.track.firstElementChild.offsetWidth;
  }

  refresh() {
    this.el.hidden = !this.enabled;
    this.setting.checked = this.enabled;
    this.el.classList.toggle('news-still', this.still);
    this.pauseButton.disabled = this.motion.matches;
    this.pauseButton.textContent = this.still ? '▶' : 'Ⅱ';
    this.pauseButton.setAttribute('aria-pressed', String(this.still));
    const label = this.motion.matches ? 'Scrolling disabled by reduced motion preference' : this.paused ? 'Resume news scrolling' : 'Pause and read the news';
    this.pauseButton.title = label;
    this.pauseButton.setAttribute('aria-label', label);
    this.offset = 0;
    this.track.style.transform = 'translateX(0px)';
    this.fill();
    this.layout();
  }

  layout() {
    const root = document.documentElement.style;
    root.setProperty('--news-height', `${this.enabled ? this.el.offsetHeight : 0}px`);
    root.setProperty('--hud-top', `${Math.ceil(document.getElementById('topbar').getBoundingClientRect().bottom) + 14}px`);
  }

  next() {
    this.track.firstElementChild?.remove();
    this.offset = 0;
    this.track.style.transform = 'translateX(0px)';
    this.fill();
    this.layout();
  }

  update(dt) {
    if (!this.enabled || this.still || this.hovered || this.focused || document.hidden) return;
    this.offset += dt * SCROLL_SPEED;
    if (this.firstWidth > 0 && this.offset >= this.firstWidth) {
      this.offset -= this.firstWidth;
      this.track.firstElementChild.remove();
      this.fill();
    }
    this.track.style.transform = `translateX(${-this.offset}px)`;
  }
}
